function js(val, indent) {
  return JSON.stringify(val, null, indent).replace(/"([^"]+)":/g, '$1:');
}

const subjects = rows.map(
  ([code, desc, lec, lab, unit, raw, faculty]) => {
    const p = U.parseScheduleWithHours(raw, lec, lab);
    return {
      subjectCode: code,
      description: desc,
      lectureHours: lec,
      labHours: lab,
      units: unit,
      section: p.section,
      daysPart: p.daysPart,
      days: p.days,
      meetings: p.meetings,
      lectureTime: p.lectureTime,
      labTime: p.labTime,
      faculty,
      rawSchedule: raw,
      excluded: false,
      parseError: null
    };
  }
);

const body = subjects
  .map((s) => '  ' + js(s, 2).replace(/\n/g, '\n  '))
  .join(',\n');

